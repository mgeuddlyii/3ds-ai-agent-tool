/*
 * httptext.h -- 取一段纯文本（给"从电脑取文件"的清单用）
 */

#pragma once

#include <stddef.h>

/* GET 一个 URL，把正文当纯文本收进 out（最多 cap-1 字节 + 结尾符）。
 *
 * ★ 返回值**必须能区分"连不上"与"服务端拒绝"**：
 *     >0  收到的字节数
 *      0  **连上了，但状态码不是 200**（http_out 里是那个码）
 *     -1  压根没连上（IP 不对 / 服务没开 / 握手失败）
 *     -2  出参不够
 *
 * 早先只有一个 0，而"403 未配对"与"连不上"都落在 0 上 ——
 * 于是互传页会把"先在电脑上填四位码"这条指引，显示给一个 IP 填错了的人。
 * 他会盯着网页上的配对码一直配不上，而真因是地址根本不对。
 * **两个原因的处置完全相反，合成一句话就等于把人引到错的方向。**
 *
 * http_out 可为 NULL（不关心状态码时）。 */
long http_get_text(const char *url, char *out, size_t cap, long *http_out);

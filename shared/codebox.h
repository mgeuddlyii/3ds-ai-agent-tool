/*
 * codebox.h -- 把模型回复里的代码块**落成文件**
 *
 * 为什么需要它：
 *   模型经常整段贴代码（```c ... ```）。在 3DS 上这段代码只能滚动着看，
 *   既不能存下来跑、也不能拷出去 —— 用户原话是「现在的版本还不能直接让我点开测试」。
 *   所以回复一落地，就把每个代码块写成沙箱里的独立文件：
 *       sdmc:/3ds/aiconsole/out/code001.c
 *   之后在对话页滑轨的「文件」格里就能直接列出、打开看。
 *
 * 三条边界：
 *   · 只写 actions_dir()（沙箱白名单里的 out 目录），**不碰别处**；
 *   · 单个文件超过 CODEBOX_MAX_BODY 就截断，并在末尾留一行说明 ——
 *     静默截断会让人以为代码本来就短；
 *   · 最多取 CODEBOX_MAX_FILES 个块，多的不写（一次回复贴十个文件也没意义）。
 */

#pragma once

#include <stddef.h>

/* 扫描 text 里的 ``` 围栏代码块，逐个写文件。
 * 返回写了几个；summary 里是给人看的一句话（写进状态行/日志）。 */
int codebox_extract(const char *text, char *summary, size_t cap);

/* 取**第一个**围栏代码块的内容（去掉围栏与语言标记），写进 out。
 * 返回写进去的字节数；0 = 这段文本里没有代码块。
 *
 * 为什么要有它：代码块落地成文件之后，用户还想要"把这串拿回来"——
 * 改一行再发一次、或者贴到别处。3DS 没有系统剪贴板，所以"复制"的落点
 * 只能是**输入框**（可编辑、可再发），这是这台机器上最接近剪贴板的东西。
 * 超长时按 cap 截断并返回实际长度（调用方自己决定怎么提示）。 */
size_t codebox_first_block(const char *text, char *out, size_t cap);

/* 给围栏里的每一行加一个**左侧竖条**（"▍ "），让代码在对话里一眼可辨。
 * 原地改写 buf；空间不够就原样返回（**绝不截断**：截断的代码比没框更糟）。
 * 围栏本身保留 —— 「复制代码」还靠它来定位块。
 *
 * 为什么在**文本层**打标记而不是画矩形：这条消息的高度是另一趟
 * （wrap_count）算出来的，只在绘制里画框会让两趟行数不一致，
 * 直接表现是滚动位置错乱 —— 那种 bug 比没有框严重得多。 */
void codebox_decorate(char *buf, size_t cap);

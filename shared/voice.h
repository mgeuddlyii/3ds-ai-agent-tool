/*
 * voice.h -- 麦克风采集（3DS MICU）
 *
 * ── 为什么要单独一层 ────────────────────────────────────────────
 * 采样本身**不碰网络也不碰 UI**：它只回答"这段时间的声音是什么波形"。
 * 而"采到的声音变成字"是 asr.c 的事。拆开的两条好处：
 *   1. 麦克风不可用（模拟器、没插麦、MICU 服务没有）时，
 *      界面能立刻给出一句人话，而不是卡在网络层猜原因；
 *   2. 录制状态机（VAD、时长上限、太短判废）可以脱离网络单独验证 ——
 *      这在 Azahar 里尤其重要，因为那里麦克风**必然**不可用，
 *      能验的就只有"优雅降级"这一段。
 *
 * ── 两个缓冲必须同量级 ──────────────────────────────────────────
 * g_ring 既是**mic 服务的共享内存**（micInit 要求 0x1000 对齐、
 * 且必须留够音频区），也是我们自己的数据源。所以它必须 ≥ 一次录音
 * 的上限，否则录音没录完就被回卷覆盖了一部分，而现象是"识别出来一段
 * 莫名其妙的声音"—— 那种错在日志里完全看不出来。
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* libctru 里最接近 16kHz 的一档：16364.479Hz。
 * 注意它是**常量**而不是 16000：写死 16000 的话，WAV 头里的采样率和
 * 实际喂给识别器的不一致，测出来会表现为"识别出来的人声变调"。 */
#define VOICE_RATE       16360

/* 一次录音的上限。5 秒 × 16360 × 2 字节（单声道 16bit）= 163600 字节，
 * 小于 VOICE_RING_SIZE（0x30000 = 196608）。
 * ⚠️ 这里**必须**先除 1000：VOICE_MAX_MS 是毫秒不是秒。
 *    写错过一次，宏算出 16360*5000*2 = 163,600,000（163MB）——
 *    不会编译报错（它只是个常量），只会变成"录满"永远触发不了，
 *    以及 asr.c 那边给静态数组开小了直接溢出。 */
#define VOICE_MAX_MS     5000
#define VOICE_MIN_MS     200     /* 比这还短就当误触，不送识别 */

#define VOICE_CAP_BYTES  (VOICE_RATE * (VOICE_MAX_MS / 1000) * 2)

/* 静音判定：连续安静超过这个毫秒数就自动收尾（省一次上行）。
 * 3DS 底噪本来就不小，所以判据用"能量明显低于起播那几帧"，
 * 不用绝对阈值 —— 绝对阈值在不同机器/增益下差别大，且不会报错，
 * 只会变成"有时识别得到有时识别不到"。 */
#define VOICE_VAD_MS     800
#define VOICE_RMS_GATE   800     /* 低于这个 RMS（0..32767）算安静 */

/* 裁首尾时的"回吐"：把 loud 区间的两端各往外放这么多，别贴着有声音的
 * 第一个采样就切。
 *
 * 起因：第一版 voice_pcm 是**贴边裁**（从第一处过门限的字节开始发），
 * 而词首的清辅音（t/k/p 那类）能量就是起头那几十毫秒，切掉等于把
 * 音节咬掉一截。2026-10-04 用两路并行资料搜集查证过：
 *   · SenseVoice 系工业部署普遍给语音段**前后各补**（vad 的
 *     speech_pad_ms=300；WebRTC VAD 前后各延 150ms），理由就是"保住
 *     起始/结尾音"、"你好啊 别把开头的你切掉"。
 *   · Whisper 那边的反方向意见是"长静音会喂出幻觉"，主张转录前去静音。
 * 两边都是**社区经验，没有官方文档级别的一致结论**，所以这里取中：
 * 一边站哪边都不对——贴边裁会咬字，补 300ms 又会把省下的带宽还回去
 * 大半。150ms 是两边都能接受的数（字节上很便宜）。
 *
 * 只在**裁过**的时候回吐（没到过门限 → 整段原样发，见 voice_pcm）。 */
#define VOICE_EDGE_PAD_MS 150

/* ---- 生命周期 ---- */

/* micInit。返回 false 表示这台机器/这个环境没有可用的麦克风。
 * ⚠️ **这是唯一的失败判定点**：调用方必须真的看返回值，
 * 否则在 Azahar 里会一路走到"请求发出去了才失败"。 */
bool voice_init(void);

/* micExit。整个进程结束前调一次；采样中调用它会停采样再退。 */
void voice_fini(void);

/* micInit 的 Result（成功时也是 0，所以这里**只用来打印诊断**）。 */
int  voice_mic_rc(void);

/* micInit 过了没有。界面靠它决定"语音按钮是亮还是灰"。 */
bool voice_available(void);

/* ---- 录制 ---- */

/* 开始采集。false = 起不来（调用方要给用户一句人话，不要闷着）。 */
bool voice_start(void);

/* 每帧调一次：把共享内存里**新增**的采样搬进本地缓冲。
 * 返回本次新增的字节数。录音已满时返回 0 并把采样停掉。 */
int  voice_pump(void);

/* 停止采集，返回总共采到的字节数（0 = 什么都没采到）。 */
int  voice_stop(void);

/* 已采集到的字节数 */
int  voice_bytes(void);

/* 已采集时长（毫秒，取整）。界面上那个"0.8s"就是它。 */
int  voice_ms(void);

/* 最近一帧的 RMS（0..32768）。VAD 与诊断都用它。 */
int  voice_rms(void);

/* 录音已经攒到 VOICE_CAP_BYTES 了（= 到上限，界面该自动收尾）。
 * 满了**必须**让调用方知道 —— 只靠"字节数不再涨"去猜是不是满了，
 * 是本项目里最容易静默失效的一类写法。 */
bool voice_full(void);

/* 静音够久（VOICE_VAD_MS）。返回 false 也可能是"压根没在录"，
 * 所以调用方要自己保证 g_rec 为真（见 sc_chat.c 的判定顺序）。 */
bool voice_silent_long(void);

/* 指向内部缓冲（PCM16 单声道小端）， len 出参拿长度。
 * 只在 voice_stop 之后、下一次 voice_start 之前有意义。
 *
 * ⚠️⚠️ 这里返回的是**有声音的那一段**（见 voice.c 里的 loud 区间），
 *      不是整段录音 —— 送 ASR 走的就是 len 个字节，静音段不发。
 *      想拿整段请用 voice_bytes()，两者别混。
 * ⚠️ 返回的指针指向 g_out 内部 —— 不要存起来用，下次录音会覆盖。 */
const void *voice_pcm(size_t *len);

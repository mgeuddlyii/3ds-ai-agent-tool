/*
 * uistr.h —— 界面文案的中英文间接层
 *
 * ── 为什么需要它 ──
 * 界面文案原本硬编码在 C 字面量里（"发送"、"设置"、"思考"…）。想让界面
 * 切英文，只有三条路：
 *   ① 满项目找中文 → 改。手工做必然漏，而漏一条的表现是"某个角落忽然
 *      冒出一句中文"，在截图里很难被当成 bug。
 *   ② 写一个双语解析器，按运行时语言挑字面量。语言必须在编译期定，
 *      一份二进制只能一种语言 —— 做不到"可切换"。
 *   ③ **把文案抽成表**（本文件）：源码里写 S(S0123)，运行时按配置挑表。
 *
 * ── 三条纪律 ──
 * 1. **编号是位置，不是内容**（和 game_id 同一条纪律，见 tools/gen_game_tables.py）。
 *    S0123 在 i18n_strings.json 里对应哪句中文，取决于抽取时的排序。
 *    所以：**改文案不要手编 uistr_table.c**，改完跑
 *        python tools/i18n_extract.py --apply
 *    它重新发号并同步改源码。手编 = 明天必错。
 *
 * 2. **诊断输出不走这里**。app_note() / boot_mark() / actions_audit() 里
 *    的中文是验收脚本的判据输入（几十条断言直接匹配中文子串）。
 *    翻成英文会让回归全红，而红的**原因不是功能坏了**。抽取脚本按
 *    "调用点"自动跳过它们。
 *
 * 3. **动作协议名永远不翻译**。file.write / fs.read 这些是协议 token，
 *    模型输出里的就是这些。界面上给用户看的说明文字可以翻译，
 *    但协议串本身出现在哪里都是原文。
 */

#pragma once

#include <stdbool.h>

/* 编号枚举（由 tools/i18n_table.py 自动生成）。
 * include 在这里而不是各自 .c，是因为 S() 宏展开后要拿 S0160 当数组下标，
 * 而**每个**用到文案的 .c 都得看得见它。 */
#include "uistr_ids.h"

/* 文案总数（= UISTR_LAST，枚举里的末项）。
 * 平时用不到 —— 源码里的编号都是枚举常量，越界编译器当场就报。
 * 它给"运行期算出来的编号"留了个检查入口。 */
extern int uistr_count(void);

/* 取一条文案。
 *
 * ★ 越界不是崩，是**回落到中文**：编号写错只可能是开发期的笔误，
 * 而"因为一个笔误让用户看到乱码"比"看到中文"糟糕得多。
 * 宁可界面上混进一句没翻的英文，也不要读越界。 */
const char *uistr(int id);

/* 当前语言。0 = 中文，1 = 英文。加第三种语言时这里跟着加。 */
int uistr_lang(void);

/* 短码是否认识（"zh" / "en"）。config.c 读盘时用它挡掉手改坏的值。 */
bool uistr_lang_known(const char *code);

/* 显示名（界面上的选项文字）："中文" / "English"。 */
const char *uistr_lang_name(int lang);

/* 切换语言并返回**实际生效**的值。
 * 传 0/1 之外的值会被忽略（防止界面算错下标把语言切成未定义态）。
 * 调用方负责 app_cfg_dirty() —— 这里不碰配置层。 */
int uistr_set_lang(int lang);

/* 初始化：文案系统就绪。app_init 里调，早于任何界面绘制。 */
void uistr_init_from_config(void);

/* 按配置里的短码生效语言（"zh" / "en"）。认不出的值退回中文。
 * 与 uistr_init_from_config 分开是因为**读配置是 app 层的活**：
 * 配置没读盘时文案系统也得能用（首启引导第一屏）。 */
void uistr_apply(const char *code);

/* ---- 源码里用的宏 ---- */

/* 取文案。S0160 这种编号来自 uistr_ids.h（自动生成的枚举），所以
 * 写错编号是**编译期**错误，不是运行时。 */
#define S(id) uistr(id)

/* 未翻译的英文占位标记。build.py 会统计它出现在 3dsx 里几次，
 * 出现在**最终产物**里就说明还有漏翻的 —— 判据不能只看源码。 */
#define UISTR_TODO "TODO-EN"
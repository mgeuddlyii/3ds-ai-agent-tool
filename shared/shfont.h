/*
 * shfont.h -- 系统共享字库切换（高风险，读完整段再用）
 *
 * ============================================================================
 * ⚠️ 先读这一段，它决定了这个模块该不该被用
 * ============================================================================
 *
 * 【它做什么】
 * 3DS 的系统字库放在一块所有进程共享的内存里（"共享字库区"）。官方只给
 * 每个区各带一套字库（神游简体 / 港繁 / 日美欧 / 韩），所以日版游戏在
 * 神游机上会因为找不到日文字形而显示乱码或方块。
 *
 * 切换字库 = 把那块内存换成另一套字库。**改的是内存，不是文件** ——
 * 重启即恢复，不写 NAND。这一点与"装 CIA 替换系统字库文件"有本质区别，
 * 后者才是真的改系统、才有砖机风险。
 *
 * 【它怎么做到】
 * 普通进程没有权限写别的进程的内存。这里用的是 **GSPWN**：3DS 的 GPU 因为
 * 硬件接线的缘故能访问一大片物理内存，而 GSP 模块**不校验**交给 GPU 的地址。
 * 于是可以伪装成"纹理拷贝"（GX_TextureCopy），让 GPU 的 DMA 引擎替我们
 * 往共享字库区写数据。这不是我们发明的技巧，SharedFontTool 就是这么做的。
 *
 * 【为什么这里必须写满警告】
 * 下面每一条都是真的，而且任一条踩中就是花屏或崩溃：
 *
 *   1. **目标地址是硬编码的，而且随 FIRM 版本变。**
 *      SharedFontTool 用的是 FIRM 6.4/8.0 时代的常量（New3DS 0x1bc00000）。
 *      而 3dbrew 的 FCRAM 布局表显示：共享字库所在的 BASE memregion
 *      起始地址是随 APPMEMTYPE 变的（New3DS type 6 → 0x0E000000，
 *      Old3DS type 0 → 0x06C00000）。
 *      → **照抄那个常量在现代系统上会写到别的用途的内存里。**
 *      本模块因此**不硬编码任何地址**：它把地址当作未知，先探测；
 *      探不到就拒绝执行（见 shfont_probe）。
 *
 *   2. **GSPWN 本身没有"被修复"，但可写范围有上限，且这个上限改过。**
 *      3dbrew 记 GSPWN 的 "Fixed in system version: None"（GPU 硬件直连，
 *      修不掉），但 GPU 能触达的 FCRAM 上限：
 *        Old3DS 0x26800000 / New3DS 0x2D800000，
 *      且 11.3.0 引入 SVC 0x59 后 New3DS 的"普通模式"上限变成 0x2D000000。
 *      → 地址在不在这个范围内，是能不能写的前提。本模块会检查。
 *
 *   3. **字库文件格式要转换。** .bcfnt 是磁盘格式（签名 'CFNT'），
 *      放进内存前要转成运行时格式（'CFNU'）并把内部指针重定位到目标地址。
 *      指针算错 → 系统读到野指针 → 直接崩。
 *
 * 【本模块的策略：能确认才做，不能确认就说不能】
 * 与其提供一个"填个地址就能跑"的危险接口，不如让它**诚实**：
 *   · shfont_probe()  探测机器上共享字库区**真**在哪 —— 探不到就是探不到；
 *   · shfont_available() 三态：可以 / 不安全 / 未知；
 *   · shfont_backup() 先把当前字库整个读出来存到 SD 卡（还原的唯一退路）；
 *   · shfont_apply()  只在 available == 可安全 时才真的写。
 * 这样即使地址探测失败，这个模块**仍然有用**：它告诉用户"你的机器上
 * 这件事做不了"，而不是让他去踩一个必崩的坑。
 *
 * ============================================================================
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>

/* 共享字库区的上限。SharedFontTool 用的是 4 × 1024 × 818 = 3,272 KB，
 * 取整到 4MB 作上界 —— 超过这个尺寸的字库文件一定不是给 3DS 用的。 */
#define SHFONT_MAX_BYTES (4 * 1024 * 1024)

/* 字库文件放哪 */
#define SHFONT_FONT_DIR "sdmc:/3ds/aiconsole/fonts"
#define SHFONT_BACKUP_DIR "sdmc:/3ds/aiconsole/fonts/backup"

typedef enum {
    SHF_OK = 0,
    SHF_ERR_NO_FILE,       /* 字库文件不在 */
    SHF_ERR_SIZE,          /* 空 / 太大 */
    SHF_ERR_FORMAT,        /* 不是 .bcfnt（签名不对） */
    SHF_ERR_NO_ADDR,       /* **探不到共享字库区地址** —— 最常见的一种，
                            * 而且它是"这台机器上做不了"，不是"包坏了" */
    SHF_ERR_OUT_OF_RANGE,  /* 地址超出了 GPU 能触达的 FCRAM 范围 */
    SHF_ERR_NO_BACKUP,     /* 没备份就想改 —— 拦下 */
    SHF_ERR_IO,            /* 读写失败 */
    SHF_ERR_GSPWN,         /* GX_TextureCopy 失败 */
    SHF_ERR_VERIFY,        /* 写完读回来对不上 */
} ShfState;

const char *shf_state_text(ShfState s);

/* --------------------------------------------------------------------------
 * 可用性三态
 *
 *   SHF_AVAIL_OK      共享字库区地址**已确认**，且落在 GPU 可写范围内
 *   SHF_AVAIL_UNSAFE  机器上这件事做不了，或者地址无法确认
 *   SHF_AVAIL_UNKNOWN 还没探测过
 *
 * ⚠️ "UNSAFE" 包含"探不到地址"这一情况。这是**刻意的设计**：
 *    探不到时我们真的不知道会写到哪，把它说成"可以做"是不负责任的。
 * ----------------------------------------------------------------------- */
typedef enum {
    SHF_AVAIL_UNKNOWN = 0,
    SHF_AVAIL_OK,
    SHF_AVAIL_UNSAFE,
} ShfAvail;

/* 探测。会把结果缓存在模块内（多次调用探一次），reason 填一句人话。
 * 这是**只读**操作：只做机型/版本判断和地址检查，不写任何内存。
 *
 * 为什么要有探测这一步：共享字库区的地址不是一个固定值，而本模块
 * **拒绝硬编码**（见头注释第 1 条）。探测的价值在于"能明确地说出
 * 这台机器行不行"，而不是猜。 */
ShfAvail shfont_probe(char *reason, size_t cap);

/* 取上次探测的结果。没探过返回 UNKNOWN。给 UI 用 ——
 * 界面要在用户按下去之前就知道该显示什么。 */
ShfAvail shfont_avail(void);

/* 探到的共享字库区地址（物理）。探不到返回 0。
 * ⚠️ 返回非 0 **不等于**可以写 —— 还要过范围检查，见 shfont_avail()。 */
unsigned int shfont_addr(void);

/* --------------------------------------------------------------------------
 * 备份 / 还原
 *
 * **改之前必须先备份。** 共享字库区是内存，重启就没了 —— 所以"还原"
 * 这件事在重启后就自动完成了。那为什么还要备份？
 *   因为**不重启**的那些场景：切了字库之后发现某些界面显示不对，
 *   想立刻切回去，而手上没有原始字库就没法切回来（官方字库是随系统
 *   加密存储的，我们读不到原版）。备份是给这种场合用的。
 *
 * 备份出来的是**运行时格式**（'CFNU'）的裸数据，长度就是区域大小。
 * 还原时原样写回去 —— 不用转换，因为它本来就是从那儿读出来的。
 * ----------------------------------------------------------------------- */

/* 把当前共享字库读出来存到 SD 卡。文件名叫 shfont_backup.bin。
 * 返回 false 表示读不出来（多半是没探到地址）。 */
bool shfont_backup(char *msg, size_t cap);

/* 有没有备份。给 UI 判断要不要显示"切回备份"这个入口。 */
bool shfont_has_backup(void);

/* 从备份还原。 */
ShfState shfont_restore(char *msg, size_t cap);

/* --------------------------------------------------------------------------
 * 切换字库
 *
 * 流程：可用性检查（不 OK 直接拒）→ 备份存在检查 → 读文件 → 格式校验
 *       → CFNT→CFNU 转换 + 指针重定位 → GSPWN 分块写 → 读回核对
 *
 * 任一步失败都**不会留下半个字库** —— 要么整个写进去，要么原样不动。
 * （做法：先在普通内存里把完整的运行时镜像拼好，全部就绪后才开始写目标
 *   区域；写的过程中若出错，用备份自动回滚。）
 *
 * 没做过备份时**直接拒绝**（SHF_ERR_NO_BACKUP）—— 这是刻意的：
 * 允许在没退路的情况下动这块内存，等于把用户扔在一个不能反悔的操作前。
 * ----------------------------------------------------------------------- */
ShfState shfont_apply(const char *name, char *msg, size_t cap);

/* 列出 fonts/ 里有哪些 .bcfnt（给 UI 和 AI 看有什么可选）。 */
#define SHFONT_NAME_MAX 60
int shfont_list(char names[][SHFONT_NAME_MAX + 1], int max, int *count_out);

/*
 * chatlog.h -- 会话记录：存下来 + 导出去
 *
 * 两个用途共用一套读写：
 *   · 持久化（JSONL）  —— 关掉再开，之前聊的还在。能被原样读回。
 *   · 导出（纯文本）   —— 卡插到电脑上能直接看，也能发给别人。
 *
 * 为什么不做成"只存 JSON，想要文本自己转"：3DS 上跑不了脚本，
 * 用户也不该为了看一眼聊天记录去装个 Python。程序顺手多写一种格式，
 * 成本是几十行，换来的是"插上电脑就能读"。
 *
 * 为什么是 **JSONL**（一行一个 JSON 对象）而不是一个大 JSON 数组：
 * 大数组要整份读进内存才能解析 —— 24 条 × 1KB 就是 24KB 的静态缓冲，
 * 在 3DS 上不是能随便开的东西。一行一条就能逐行读、逐行解析，
 * 内存只要一行的大小；顺带还让"人拿文本编辑器打开"时能看懂个大概。
 *
 * 上限：最多 40 条、单条 1KB。太长的历史既没人回看，也会把 SD 写爆。
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>

/* 单条文本上限，和界面的显示上限一致 —— 存的本来就是屏上那点东西。 */
#define CHATLOG_TEXT_MAX 1024

/* 一次会话最多留多少条。滚动窗口：超了丢最早的。 */
#define CHATLOG_MAX_TURNS 40

const char *chatlog_dir(void);    /* sdmc:/3ds/aiconsole */
const char *chatlog_path(void);   /* sdmc:/3ds/aiconsole/chat.json */

/* --------------------------------------------------------------------------
 * 写：open → item* → close 的状态机
 *
 * 不设计成"把数组传进来"，是因为消息本来就活在界面自己的 g_msgs 里，
 * 为了落盘再复制一份到内存（40 × 1KB = 40KB，在 3DS 上不是小数目）不值当。
 * 调用方遍历自己的数组、逐条喂进来即可。
 *
 * human = false → JSON，用于持久化（下次能原样读回）
 * human = true  → 纯文本，用于导出（带时间戳的文件名）
 *
 * out_path 非空时回填实际写出的路径，方便界面提示"存哪儿了"。
 * ----------------------------------------------------------------------- */
bool chatlog_open(bool human, char *out_path, size_t cap);
void chatlog_item(bool mine, const char *text);
bool chatlog_close(void);

/* --------------------------------------------------------------------------
 * 读：每解析出一条就回调一次
 *
 * 回调里的 text 指向**模块内部的缓冲**，下一次回调就会被覆盖 ——
 * 要留住就自己拷走。这样避免为了读盘再开一个 40KB 的大数组。
 * 返回读到的条数（0 = 文件不在 / 读失败 / 格式不对）。
 * ----------------------------------------------------------------------- */
typedef void (*ChatlogFn)(bool mine, const char *text, void *user);
int chatlog_load(ChatlogFn fn, void *user);

/* 上一次 chatlog_load 里有几条因为超过 CHATLOG_TEXT_MAX 被截短了。
 * 正常情况下永远是 0；非 0 只有一个解释：卡上的 chat.json 不是本程序
 * 写的（手改过，或来自另一个版本）。界面应当把它说出来 ——
 * 一条被腰斩的对话看起来跟原文一模一样，不说就等于骗人。 */
int chatlog_oversize_count(void);

/* 读盘用的行缓冲由 chatlog_load 按需分配并留着复用（见 chatlog.c 的说明）。
 * 这个函数把它交还回去 —— 只在"确定不再读历史"时才需要调，
 * 平时不调也不泄漏（进程退出由系统回收）。 */
void chatlog_reader_free(void);

bool chatlog_exists(void);

/* --------------------------------------------------------------------------
 * 追加一条（JSONL，不动已有内容）
 *
 * ── 为什么必须有这个函数，而不是继续用 open/item/close ──
 * chatlog_open(false) 用的是 **"wb"**：**打开那一刻文件就被清空**，
 * 然后逐条重写。这意味着两件坏事：
 *   ① 断电/崩溃/强退发生在 open 与 close 之间 → **整份历史变成 0 字节**；
 *   ② 写入的内容只来自内存里的消息表（上限 CHAT_MAX=24），
 *      于是每次保存都把磁盘上更早的内容**截短到 24 条**。
 * 用户看到的就是"重启后对话没了"。
 *
 * 追加写没有这两个问题：不打开就不动，打开也只往后写。
 * 文本里带换行/引号由内部的 put_str 转义，落盘永远是一行一条。
 * ----------------------------------------------------------------------- */
bool chatlog_append(bool mine, const char *text);

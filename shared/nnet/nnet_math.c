/*
 * nnet_math.c — 定点超越函数实现
 *
 * 实现要点（每条都是踩过才知道的）：
 *
 * 1. **Q15 定点 vs VFP 乘加哪个快？**
 *    在 ARM11 上 (int32 << 15) 之间的乘法是 1 拍（mla），
 *    而 fp32 乘加是 vmla.f32，**也要 1 拍** —— 但 VFP 有个坑：
 *    连续 fp32 运算在不同精度模式间切换会触发 spc_csr_f32，
 *    流水要排空（约 10~20 拍）。定点路径全在整数域，
 *    与前面刚跑完的 int8 点积共用流水，不断水。
 *    真正的收益在这里，不是"乘法拍数少"。
 *
 * 2. **为什么不用查表 + 线性插值？**
 *    表法确实更快，但表要放 .rodata（+4KB）而且插值要一次乘法，
 *    在只有 8 位有效位的场景下收益不到 5%。多项式方案的精度
 *    已经远超需求，换来的**无表依赖**在插件场景里更值钱
 *    （少一块 rodata 就少一处可能的踩内存）。
 *
 * 3. **饱和必须在每一步做，不能只夹输入。**
 *    Q15 的累加器是 int32，3 次多项式连乘很容易溢出 2^31。
 *    溢出在 ARM11 上是**饱和到2^31-1**（不抛异常），
 *    于是结果变成一个巨大的正数 —— 后面 exp 全是 1，
 *    softmax 归一化后变成均匀分布，看起来"模型没学到东西"，
 *    但你永远查不到原因。
 */
#include "nnet_math.h"

#include <math.h>   /* selftest 里要与 libm 对比 */
#include <stdint.h>

/* ---- 定点工具 -------------------------------------------------------- */

static inline int32_t clamp_i32(int32_t v, int32_t lo, int32_t hi)
{
    return v < lo ? lo : (v > hi ? hi : v);
}

/*
 * float -> Q15（返回 0..32767 对应 0.0..1.0）。
 * 三个必须挡的情况：
 *   NaN   -> 0   （NaN 的所有比较都是false，
 *                  不显式判就会掉进下面的 v<0 或 v>hi 的分支缝隙）
 *   >1   -> 32767
 *   <0   -> 0
 */
static inline int32_t f2q15(float f)
{
    if (!(f > 0.0f)) return 0;            /* 顺手挡掉 NaN（NaN > 0 为假）*/
    if (f >= 1.0f)   return 32767;
    return (int32_t)(f * 32768.0f + 0.5f);
}

/* Q15 -> float */
static inline float q15_2f(int32_t q)
{
    return (float)q * (1.0f / 32768.0f);
}

/*
 * 定点乘法：(a/32768) * (b/32768) = ab / 2^30
 * 写成 (a*b)>>15 而不是 (a*b)>>30 是为了**保留精度**：
 * Q15 只有 15 位小数，一次右移 15 位意味着每乘一次丢 1 位精度。
 *
 * 折中方案（业界常用）：把 a 保持在 Q15，b 转到 Q30，
 * 于是 a*b>>15 得到 Q15，中间值 ab 最大 32767*2^30 ≈ 2^45，
 * int32装不下 —— 所以 b 的 Q30 要按需缩放。
 *
 * 这里的做法更简单也更安全：**乘法后饱和到 int32 再右移**。
 * 精度损失实测 < 1e-5，相对误差远小于 Q15 的 3e-5 量化步长。
 */
static inline int32_t qmul(int32_t a, int32_t b)
{
    int32_t p = (int32_t)(((int64_t)a * (int64_t)b) >> 15);
    return clamp_i32(p, -32768, 32767);
}

/* ------------------------------------------------------------------ */
/* expf                                                                */
/* ------------------------------------------------------------------ */

/*
 * e^x = 2^(x/ln2) = 2^k * 2^f，其中 k = round(x/ln2)，f∈[-0.5, 0.5]
 * 2^f 用 5 阶多项式（|f|≤0.5 时截断误差 < 1e-7，比 Q15 精度深得多）
 *
 * 为什么这样分：2^k 只需调整指数（vmov/scale 级别的操作），
 * 而 2^f 的多项式只在小范围内工作 —— 两部分各自都很准。
 */
float nnet_expf(float x)
{
    /* NaN 必须先挡。NaN 进来时下面所有比较都为假，
     * 最后会落到 range check 的 else 分支返回一个魔数 ——
     * 那比直接返回 0 难查得多。*/
    if (x != x) return 0.0f;

    /* 饱和区间。±80 对应 fp32 的安全边界：
     * e^80 = 5.5e34，e^-80 = 1.8e-35，两者都还在 fp32 范围内。 */
    if (x > 80.0f)  return 5.540622e34f;
    if (x < -80.0f) return 0.0f;

    /* 特殊情况：ln2 = 0.693147...，反值为 1.442695
     * 单核浮点除法 14 拍，而这里每个 token 要调 2 次 expf。 */
    {
        const float LOG2E = 1.4426950408889634f;
        float  y = x * LOG2E;
        int32_t k;
        float  f;

        /* 负数向上取整、正数向下取整？统一用 (int)(y>=0?y+0.5:y-0.5)
         * 得到「最近整数」，保证 f∈[-0.5,0.5]。
         * 用 lrintf 会走库函数（依赖当前舍入模式），不可控。 */
        k = (int32_t)(y + (y >= 0.0f ? 0.5f : -0.5f));
        f = y - (float)k;

        /* 2^f 的 5 阶泰勒（Horner）
         * ln2 的幂级数系数：1, 1/2, 1/6, 1/24, 1/120 */
        {
            const float c1 = 0.6931471805f;
            const float c2 = 0.2402265069f;   /* 1/6  * ln2^2 */
            const float c3 = 0.0555041087f;   /* 1/24 * ln2^3 */
            const float c4 = 0.0096181291f;   /* 1/120* ln2^4 */
            /* p = 1 + c1*f + c2*f^2 + c3*f^3 + c4*f^4
             * f∈[-0.5,0.5]，4 阶截断误差 ≈ 0.5^5/120 ≈ 2.6e-5，
             * 相对 Q15 量化步长 3e-5 已在同一量级 —— 再多一项是浪费。 */
            float p = 1.0f + f * (c1 + f * (c2 + f * (c3 + f * c4)));
            /* 2^k：用 ldexpf 会走库函数；这里用位拼装，
             * 但必须先夹住 k，否则指数位溢出会变成 0 或 Inf。
             * x∈[-80,80] → k∈[-116,116]，
             * 落在 fp32 正常数范围 [-126,127] 内，但要给饱和留余量。 */
            {
                int32_t e = clamp_i32(k + 127, 1, 254);
                union { uint32_t u; float f; } sc;
                sc.u = (uint32_t)e << 23;
                return p * sc.f;
            }
        }
    }
}

/* ------------------------------------------------------------------ */
/* tanh                                                                */
/* ------------------------------------------------------------------ */

/*
 * tanh(x) = 2·sigmoid(2x) - 1 = (2 - 2·e^(-2x)) / (1 + e^(-2x))
 *
 * 走 e 的多项式而不是独立实现 tanh：ARM11 上重新推导一套
 * tanh 的有理逼近要多花几百字节 flash 和一堆系数，
 * 而复用 nnet_expf 只多一次乘法 —— 收益是正的。
 *
 * 关键技巧：**用 e^(-2|x|) 的对称式**，
 *     tanh(x) = sign(x) · (1 - 2/(e^(2|x|) + 1))
 * 这样 x 只以绝对值进入exp 路径，不会因为符号丢精度。
 */
float nnet_tanhf(float x)
{
    if (x != x) return 0.0f;               /* NaN */
    if (x >  9.0f) return  1.0f;          /* tanh(9)=1-3e-8，fp32 已经饱和 */
    if (x < -9.0f) return -1.0f;

    {
        /* ⚠️⚠️ 这里传的是 **2·|x|**，不是 2·|x|·ln2，也不带任何 ln2。
         *
         * 踩了两次坑才写对，记录下来免得再犯：
         *
         *   第 1 次：写成 a * (2.0f * LOG2E) = a*2.8854
         *   第 2 次：改成 a * TWO_LN2 = a*1.3863        <- 还是错
         *
         * 两次都错在同一个地方：**以为公式里的 e^(2x) 需要 ln2 换算**。
         * 完全不需要 —— e^(2x) 就是 exp(2x)，直接把 2x 交给
         * nnet_expf 即可。ln2 只在 nnet_expf **内部**做 2^k 分解时才出现，
         * 那已经封装在里面了，调用方再乘一次就是把它当因子用了。
         *
         * 第 2 次那个错误特别阴险：TWO_LN2 的值(1.3863)离真值 1.0 不远，
         * 在 x 小时误差看起来像"精度不够"，而实际上 tanh(0.5)
         * 会算成 0.3333 —— 恰好是 1/3，一眼能看出是算错了但很难联想到常数。
         *
         * math_probe.py 的逐点对比抓到了它（真值 0.4621 vs 实得 0.3333）。
         * **改这个文件的常数后必须跑 math_probe.py。**
         */
        float a  = x < 0.0f ? -x : x;     /* |x| */
        int32_t sgn = (x < 0.0f) ? -1 : 1;
        float e2;

        /* exp(2|x|) 恒 ≥ 1，用 u = e2 - 1 ∈ [0, ∞)
         * tanh = (e2-1)/(e2+1) = u/(u+2)
         * —— 这样 1 是精确值，不会因为 exp 的常数误差整体偏移。*/
        e2 = nnet_expf(a + a);             /* 2·|x|。写 a+a 而不是 2.0f*a：
                                             * 后者会被 gcc 变成 f32 乘，
                                             * 多一次舍入。虽然误差只有 1ulp，
                                             * 但这里没有任何理由多一次舍入。 */
        {
            float u  = e2 - 1.0f;
            float th = u / (u + 2.0f);
            th = clamp_i32((int32_t)(th * 32768.0f + 0.5f), -32767, 32767)
                 * (1.0f / 32768.0f);
            return sgn < 0 ? -th : th;
        }
    }
}

/* ------------------------------------------------------------------ */
/* 1/sqrt(x) 与 1/x                                                    */
/* ------------------------------------------------------------------ */

/*
 * rsqrt 的定点做法：
 *   用 IEEE754 单精度的**魔数近似**起步，再做 2 轮牛顿迭代。
 *
 * 为什么选0x2F7B：它是最常用的 magic 倒数平方根，
 * 初始误差 < 3.4%，两轮牛顿后误差 < 1e-6。
 *
 * 牛顿迭代 r ← r·(1.5 - 0.5·x·r²)
 * 每轮 2 次定点乘法，VFP 上是 2 条 vmla.f32（各 1 拍）。
 * 换成软浮点的 sqrtf + 除法，是几百到上千拍 —— 这才是收益点。
 */
float nnet_rsqrtf(float x)
{
    union { float f; uint32_t u; } v;
    float r;

    if (x != x) return 0.0f;               /* NaN */
    if (x <= 0.0f) return 0.0f;            /* 见头文件的理由 */
    if (x > 3.4e38f) return 0.0f;          /* Inf/溢出 */

    v.f = x;
    /*
     * 魔数近似的标准做法（Quake III 的 fast inverse sqrt）：
     *     y = 0x5F375A85 - (bits >> 1)
     * 只有一个赋值。**不要**先做一次 (bits>>1) + 0x1FBD1DF5 之类的
     * "预偏置" —— 那样初值会偏掉半个 binade，
     * 两轮牛顿后仍有约 0.5% 误差，压不下去。
     */
    v.u = 0x5F375A85u - (v.u >> 1);
    r = v.f;

    /* 2 轮牛顿迭代 */
    r = r * (1.5f - 0.5f * x * r * r);
    r = r * (1.5f - 0.5f * x * r * r);

    /* 夹住结果：x 是 int8 量化过的激活，rsqrt 的值域很窄，
     * 但一旦输入出意外，rsqrt 会往 0 或 Inf 跑。 */
    if (r > 1e30f) return 1e30f;
    if (r < 1e-30f) return 0.0f;
    return r;
}

float nnet_rcp(float x)
{
    if (x != x) return 0.0f;
    if (x == 0.0f) return 0.0f;

    /* 直接用 VFP 的 vdiv 指令（1 条 vdiv.f32）。
     * 这里**不用**牛顿迭代：rcp 只在 LayerNorm 的 mean 和
     * softmax 的 sum 上调（共 10 次/token），
     * 而 vdiv.f32 在 ARM11 上是 14 拍，
     * 牛顿迭代反而要 2 次乘 + 1 次减的依赖链，差不多。
     * 所以保留硬件除法是对的 —— 不是所有东西都该手写。 */
    return 1.0f / x;
}


/* x^e（只服务采样的 1/T 次幂）                                         */
/* ------------------------------------------------------------------ */

/*
 * ln(x) 的 Q15 定点版。
 *
 * 为什么自己写而不用 logf：newlib 的 logf 是软浮点，而且要先做
 * 区间归约 + 至少7 阶多项式 + 最终的指数拼装 ——
 * 这里只需要 x∈(0,1]（概率）与 6 位以内的有效结果。
 *
 * 做法：把 x 用 2 的幂缩放到 [1/sqrt2, sqrt2]，
 * 此时 ln(x) ∈ [-0.3466, +0.3466]，用 atanh 级数
 *     ln(x) = 2·(z + z³/3 + z⁵/5 + ...)，z = (x-1)/(x+1) ∈ [-0.1716, 0.1716]
 * z⁵/5 已经 < 7e-7，再加项没有意义（Q15 量化步长是 3e-5）。
 */
static float nnet_lnf(float x)
{
    union { float f; uint32_t u; } v;
    int32_t e;
    float m, z, z2;

    if (x != x || x <= 0.0f) return -88.0f;   /* 越界用大负数，
                                                * nnet_powf 会乘 0 出 0 */

    v.f = x;
    e = (int32_t)((v.u >> 23) & 0xFFu) - 127;   /* 提指数 */
    v.u = (v.u & 0x007FFFFFu) | 0x3F800000u;   /* 尾数归到[1,2) */
    m = v.f;

    /* 让尾数落进 [1/sqrt2, sqrt2)：m>sqrt2 时除 2。
     * sqrt2 的 f32 位模式是 0x3FB504F3。 */
    if (m > 1.4142135f) { m *= 0.5f; e += 1; }

    z    = (m - 1.0f) / (m + 1.0f);
    z2   = z * z;
    /*
     * ln(x) = 2·atanh(z) = 2·(z + z³/3 + z⁵/5 + z⁷/7 + z⁹/9 + …)
     *
     * ⚠️⚠️ 正确的折法（这里踩了三次坑，每次都是"看起来能跑"的）：
     *
     *     ln(m) = 2z + 2z³/3 + 2z⁵/5 + 2z⁷/7 + 2z⁹/9 + …
     *           = 2z·( 1 + z²·[ 1/3 + z²/5 + z⁴/7 + z⁶/9 + … ] )
     *                   ^^^^^^^ 那个 1 在括号内、z² 之外
     *                   ^^^^^^^^^^^^^^^^^^^^^^^^^^^ 这一坨才是 sh
     *
     * 所以 Horner 折出的是 **从 z² 起的那一段**，
     * 而 z²·sh 才是要跟 1 相加的部分：
     *     sh = 1/3 + z²/5 + z⁴/7 + z⁶/9+ …
     *     lnm = 2z·(1 + z²·sh)
     *
     * 三次错法与症状（都是 math_probe.py 逐点对比抓到的，
     * 单点测试全部"看起来合理"）：
     *   ① lnm = 2z·sh                → 差 3 倍（丢了整个 z·(1+…)）
     *                                       ln(0.9) 得 -0.0351，真 -0.1054
     *   ② lnm = 2z·(1 + sh)          → sh 整体错位一级
     *                                       ln(0.9) 得 -0.1404，真 -0.1054
     *   ③ Horner 从 1/3 起步往上折     → 同一类错位，换个方向犯
     *
     * **记住这条对照：sh 里没有常数 1，1 在 sh 外面。**
     * 展开检查：2z(1 + z²·sh) = 2z + 2z³/3 + 2z⁵/5 + … ✓
     *
     * z 的范围：m ∈ [1/√2, √2] → z ∈ [-0.1716, 0.1716]
     * z⁹/9 < 1.2e-9，远低于 Q15 量化步长 3e-5，四项足够。
     */
    {
        float sh = 0.1111111111f;/* 1/9  ← 从最低次起 */
        sh = 0.1428571429f + z2 * sh;      /* 1/7     */
        sh = 0.2f          + z2 * sh;      /* 1/5     */
        sh = 0.3333333333f + z2 * sh;      /* 1/3     */
        {
            float lnm = 2.0f * z * (1.0f + z2 * sh);
            /* e 是尾数归一化时提出来的 2 的幂指数，
             * 所以 ln(x) = ln(m) + e·ln2。 */
            return lnm + (float)e * 0.6931471805599453f;
        }
    }
}

/*
 * x^e = exp(e·ln x)
 *
 * 调用方（nnet_pick）已把 e 夹在 [0.25, 20]，
 * 且 x 是概率 ∈ (0,1]，所以 e·ln(x) ∈ [-55, 0]——
 * 完全落在 nnet_expf 已实测过的工作区里。
 */
float nnet_powf(float x, float e)
{
    if (x != x || e != e) return 0.0f;
    if (x <= 0.0f) return 0.0f;
    if (x == 1.0f) return 1.0f;
    /* e·lnx 不会超过 -55，但仍然过一遍 expf 的饱和区间 ——
     * 万一调用方改了 e 的夹取范围，这里不会静默出 NaN。 */
    return nnet_expf(e * nnet_lnf(x));
}

/* ------------------------------------------------------------------ */
/* 精度自检                                                            */
/* ------------------------------------------------------------------ */

float nnet_math_selftest(int32_t *out_exp, int32_t *out_tanh,
                         int32_t *out_rsqrt, int32_t *out_bad)
{
    /* 采样点刻意覆盖三段：
     *   [-80,-20]  softmax 的真实工作区（减过 max 后）
     *   [-20,0]   GELU 的主要区间
     *   [0, 80]    饱和区与上界行为
     * 另加 rsqrt 的 [1e-6, 1e6]。*/
    static const float xs[] = {
        -80.f,-60.f,-40.f,-20.f,-12.f,-8.f,-5.f,-3.f,-2.f,-1.5f,
        -1.f,-0.7f,-0.5f,-0.25f,-0.1f,-0.01f, 0.f,
         0.01f,0.1f,0.25f,0.5f,0.7f,1.f,1.5f,2.f,3.f,5.f,8.f,12.f,20.f,80.f
    };
    const int N = (int)(sizeof xs / sizeof xs[0]);
    float me = 0.0f, mt = 0.0f, mr = 0.0f;
    int i, bad = 0;

    for (i = 0; i < N; i++) {
        float x = xs[i];
        float g, d;

        /* expf：只测负半轴（正半轴上界饱和是刻意的行为） */
        if (x <= 0.0f) {
            g = expf(x);
            d = nnet_expf(x) - g;
            if (d < 0) d = -d;
            /* 相对误差才是有意义的量：e^-80 只有 1.8e-35，
             * 绝对误差 1e-35 看着很小但相对误差可能巨大。*/
            if (g > 1e-30f && d / g > me) me = d / g;
            if (nnet_expf(x) < 0.0f) bad |= 1;
        }

        /* tanhf：全区间 */
        g = tanhf(x);
        d = nnet_tanhf(x) - g;
        if (d < 0) d = -d;
        if (d > mt) mt = d;
        if (nnet_tanhf(x) < -1.0001f || nnet_tanhf(x) > 1.0001f) bad |= 2;

        /* rsqrt：正半轴 */
        if (x > 0.0f) {
            g = 1.0f / sqrtf(x);
            d = nnet_rsqrtf(x) - g;
            if (d < 0) d = -d;
            if (g > 1e-20f && d / g > mr) mr = d / g;
            if (nnet_rsqrtf(x) < 0.0f) bad |= 4;
        }
    }

    /* NaN / Inf / 负数输入：必须全部安全返回，且不能崩 */
    {
        volatile float nan_v = 0.0f;
        nan_v = nan_v / nan_v;             /* NaN */
        if (nnet_expf(nan_v) != 0.0f) bad |= 8;
        if (nnet_tanhf(nan_v) != 0.0f) bad |= 8;
        if (nnet_rsqrtf(nan_v) != 0.0f) bad |= 8;
        if (nnet_rcp(0.0f) != 0.0f) bad |= 8;
        if (nnet_rsqrtf(-1.0f) != 0.0f) bad |= 16;
        if (!(nnet_expf(1e30f) > 0.0f)) bad |= 16;   /* 正溢出给钳位值 */
        if (!(nnet_expf(-1e30f) == 0.0f)) bad |= 16; /* 负溢出给 0 */
    }

    if (out_exp)   *out_exp   = (int32_t)(me * 1e9f);
    if (out_tanh)  *out_tanh  = (int32_t)(mt * 1e9f);
    if (out_rsqrt) *out_rsqrt = (int32_t)(mr * 1e9f);
    if (out_bad)   *out_bad   = bad;

    /* 返回一个能一眼看出量级的数：最大误差的纳倍率 */
    return me > mt ? me : (mt > mr ? mt : mr);
}

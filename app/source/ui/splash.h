/*
 * splash.h -- 启动进度屏
 *
 * 目的：启动期的重活（网络栈、配置、性能探测）原先全挤在"出第一帧之前"，
 * 用户看到的是黑屏一段然后界面突然冒出来 —— 观感上就是"卡"。
 *
 * 这里把启动拆成若干个**阶段**，每阶段之间画一帧进度：
 *   - 用户立刻看到界面（"程序活着"）
 *   - 进度条持续推进（"它在干活，不是死了"）
 *   - 没有一帧承担全部重活，所以不会长时间不响应
 *
 * 为什么不是"后台线程预加载"：
 *   3DS 的 soc/httpc/APT 服务句柄有线程亲和性，把 socInit 挪到子线程
 *   再在主线程用 curl 是踩过坑的做法（服务线程归属不明 → 随机失败）。
 *   分帧方案同样消除"长黑屏"，但不碰线程安全的雷区 —— 收益的绝大部分
 *   在观感，而观感不需要动线程。
 *
 * 注意：这个屏不注册进 Screen 表。它是**启动专属**的、不进返回栈、
 * 不接受按键 —— 它只在 main 的启动阶段被直接绘制。
 */

#pragma once

/* 启动阶段总数（进度条分母）。改阶段划分要同步改这个数。 */
#define SPLASH_STEPS 5

/* 画一帧启动进度。step 是 0..SPLASH_STEPS：
 *   0 = 刚开始，还没做任何事
 *   i = 已完成第 i 步
 * label 是当前正在做的事（显示在进度条下方），可为 NULL。 */
void splash_frame(int step, const char *label);

/* 收尾：画最后一帧"就绪"，并让进度条走满。 */
void splash_done(void);

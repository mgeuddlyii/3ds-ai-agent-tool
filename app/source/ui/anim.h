/*
 * anim.h -- 轻量帧驱动动画
 *
 * 目的：把"界面元素按时间平滑过渡"这件事收成一个极小的模块，
 * 让调用方（主要是 w_button）不用自己写时间戳、缓动曲线、状态判定。
 *
 * 设计约束（为什么长这样）：
 *
 * 1. **按帧推进，不按毫秒。** 本 app 的主循环被 r_end() 的
 *    gspWaitForVBlank() 锁在 60fps（模拟器里慢得多），所以"帧"就是
 *    最可靠的时基 —— 不依赖 osGetTime（它在模拟器里和真机量化不同），
 *    也不会因为某一帧卡了就把动画算到离谱的位置。
 *
 * 2. **单向目标 + 自动反向。** 调用方只说"我想要 1（按下）"或
 *    "我想要 0（松开）"，anim_tick 负责朝目标推进。中途改目标不用
 *    重置 —— 这正是"按下时手指滑走了"要的行为。
 *
 * 3. **缓动固定用 ease-out。** 不做可配置曲线：在这个 app 里所有
 *    位移动画都是"快速起步、缓收尾"最自然，多一个参数只会多一处
 *    不一致。曲线是二次式，两次整数乘除即可，ARM11 上也便宜。
 *
 * 4. **值域固定 0..ANIM_ONE（1024）。** 定点整数，避免浮点在按钮
 *    绘制这种每帧多次调用的路径上开销。调用方自己按需缩放。
 */

#pragma once

#include <stdbool.h>

/* 定点满量程。取 1024 是因为它既能给足插值精度，
 * 又能让 "v * x / 1024" 这种缩放保持较小的中间值。 */
#define ANIM_ONE 1024

/* 动画时长（帧）。12 帧 @60fps = 200ms —— 快到不拖沓，
 * 又慢到能看清过渡。模拟器低帧率下会更慢，反而更容易观察。 */
#define ANIM_FRAMES 12

typedef struct {
    int  v;        /* 当前值，0..ANIM_ONE */
    int  target;   /* 目标值，0 或 ANIM_ONE */
} Anim;

/* 归零：值=0、目标=0。可在每个状态对象创建时调一次。 */
void anim_reset(Anim *a);

/* 设定目标：0 = 收起，非 0 = 展开。只改目标，不改当前值。 */
void anim_set(Anim *a, bool on);

/* 推进一步（每帧调一次）。返回 true 表示这一帧值有变化
 * —— 调用方可据此决定是否需要重绘。 */
bool anim_tick(Anim *a);

/* 当前值归一化到 0.0..1.0。 */
float anim_value(const Anim *a);

/* 已完成（|v - target| == 0）。 */
bool anim_done(const Anim *a);

/* ---- 自检（验收用）----
 * 为什么需要：动画是**时序**行为，单张截图看不出来（两个时刻的样子
 * 各自都正常，错的是"中间没有过渡"）。所以让动画模块自己证明三件事：
 *   1. 从 0 到满量程需要**多帧**推进（不是一步到位）
 *   2. 推进过程中值**单调递增**且**严格在中间**（不是直接跳到目标）
 *   3. 中途改目标能**立刻反向**（手指按下后又滑走的情形）
 * 返回通过的项数（满分 ANIM_SELFTEST_TOTAL）。 */
#define ANIM_SELFTEST_TOTAL 3
int anim_selftest(void);

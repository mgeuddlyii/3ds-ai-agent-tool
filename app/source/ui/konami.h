/*
 * konami.h -- 隐藏入口与密码门
 */

#pragma once

#include <3ds.h>      /* u32 —— 按键掩码是 libctru 的 u32，不是 stdint */
#include <stdbool.h>

/* 记一次按键（设置屏在调安全等级时喂进来）。
 * 内部维护"连点计数"与"密码进度"，都不需要调用方操心。
 *
 * ★ 参数必须是 **u32**，不能是 int。
 *   3DS 的方向键是"通用方向"别名：KEY_UP = KEY_DUP | KEY_CPAD_UP，
 *   而 CPAD 那几位在高位，于是 KEY_DOWN = BIT(7) | BIT(31)
 *   在 int 下是**负数**。用 int 收参数再写 `if (key <= 0) return;`，
 *   两个下键会被静默丢掉 —— 症状是"密码明明输对了却不过"，
 *   而且日志里那两个键**一行都没有**，因为它压根没进比对。
 *   （2026-10-06 00:1x 实测：progress 卡在 2/10 就是这个原因。） */
void konami_feed(u32 key);

/* 连点六下版本号之后，会进入一个短暂的"提示"状态。
 * 这一屏要说清"你在做什么"以及"接下来要什么"，因为
 * 密码门最糟的失败是用户不知道自己在输什么。 */
bool konami_prompt_active(void);

/* ★★ 密码门**正在接管键盘**（提示态 或 正在收密码）。
 *
 * 给屏幕层用的**总闸**：返回值非 0 时，屏幕必须把这一帧的按键
 * **全部吞掉**（只喂给 konami_feed，不再做导航/改值/返回）。
 *
 * 为什么不能只用 konami_prompt_active()（2026-10-16 真机反馈）：
 *   提示被**第一个**方向键关掉之后，s_prompt 就变 false 了，
 *   但这时才刚刚开始收密码 —— 于是屏幕层以为"没事了"，继续拿方向键
 *   去挪光标。用户看到的是"一按密码，选中的行就跟着跑"，
 *   而且密码永远输不完（←→ 还在改当前行的值）。
 *   所以判据必须是"提示态 **或** 正在收密码"这一个或起来的状态。 */
bool konami_capturing(void);

/* 用户主动取消（不是 START —— 见 konami.c 里那段说明：
 * main.c 全局把 START 当退出键，走不到这里）。
 * 屏幕层在弹窗期间按 R / 点「取消」按钮时调用。 */
void konami_cancel(void);

/* 提示态收到任意键 → 清掉，回到正常界面。 */
void konami_dismiss_prompt(void);

/* 密码是否已通过。通过后本次开机内有效（不落盘 ——
 * 落盘等于把密码的明文留在卡上，���一份 config.json 就能读到）。 */
bool konami_unlocked(void);

/* 密码进度（已对上几个键）。**只给诊断用** ——
 * 2026-10-06 00:0x 那次"KONAMI 码 FAIL 输对了却没过"就是靠它
 * 定位到"第几个键开始错位"的：光看"没过"两个字，什么都推不出来。 */
int konami_progress(void);

/* 密码一共几个键。**给界面用的**：弹窗要画进度点、要写"N / M"。
 * 硬编码 10 的话，改了密码长度就会在界面上说谎（而且不会编译报错）。 */
int konami_len(void);

/* 把密码门复位（离开设置屏时调用）。
 * **不清 s_unlocked** —— 那表示"本次开机已通过"，离开再进来不该重输。 */
void konami_reset(void);

/* ★ 只给测试用：连"已解锁"一起清掉。
 *
 * 为什么需要它：`konami_reset()` 刻意不清解锁状态（那是产品行为），
 * 于是探针里"上一个用例解锁了"会污染后面每一个 ——
 * 2026-10-06 00:2x 那次实测里，密码用例通过之后，
 * 后面三条"必须被拒"的断言全变成了假失败（ok=68 fail=4）。
 * 测试之间要隔离，产品行为不该因此改动，所以单开一个接口。 */
void konami_test_reset_all(void);

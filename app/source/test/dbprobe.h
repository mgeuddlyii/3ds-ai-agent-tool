/*
 * dbprobe.h -- 豆包通道探针（**要联网，不进常规回归**）
 *
 * 与 amprobe 的分工：
 *   amprobe  探"这台机器给不给 am:u" —— 纯本地，不联网。
 *   dbprobe  探"豆包这条线通不通" —— 要联网 + 卡上要有登录态。
 *
 * 为什么单独一个探针，而不是让 sc_chat 顺手报一下：
 * 它的价值在于**可重复**。豆包这条链路涉及的环节太多了（TLS 1.2 →
 * CA → 登录 cookie → 设备参数 → 三层 JSON 的 SSE），任何一环出问题
 * 表现都差不多是"没回复"。探针把每一环的判据分开写下来，
 * 下次出问题能直接看出是哪一环断的，而不用从头猜。
 *
 * ⚠️ 它**不加进 azahar_test.py 的常规趟次**：常规回归必须离线可跑、
 * 结果稳定；而这条依赖网络和账号，跑红是常态。
 * 要验豆包时手工在 autorun 里写一行 `dbprobe`。
 */


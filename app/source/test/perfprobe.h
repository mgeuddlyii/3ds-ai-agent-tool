/*
 * perfprobe.h -- 推理耗时的可重复测量（优化前后的唯一判据）
 *
 * 存在的理由：perf_count.py 给的是**静态算力分解**（MAC 与字节），
 * 它能指出「谁最重」，但不能回答「改完之后快了多少」。
 * 而优化如果只有静态理由、没有前后实测，
 * 就会出现上一轮 8 路展开那种情况：**纸面指令数降了 19%，实际更慢**。
 *
 * ⚠️ 判据必须是「每 token 耗时」这个**单调量**，不要用帧号。
 * 帧号受渲染负载、模拟器调度、宿主 CPU 争用影响，
 * 同一次改动前后差 5% 完全在噪声内 —— 那样任何"优化"都能自证成功。
 *
 * 计时用 svcGetSystemTick（268MHz 硬件计数器），
 * 换算成毫秒用整数运算：%.1f 会把 newlib 的 dtoa 拖进运行路径
 * （Azahar 小主栈上炸过，见 widgets.c 的同类注记）。
 */

